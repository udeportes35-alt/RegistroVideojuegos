public void agregarFila(String titulo, String genero, double precio) {
    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tblVideojuegos.getModel();

    modelo.addRow(new Object[]{titulo, genero, precio});
}

public void eliminarFila(int fila) {
    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tblVideojuegos.getModel();    

    modelo.removeRow(fila);
}

